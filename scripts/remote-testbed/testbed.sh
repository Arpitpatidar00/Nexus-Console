#!/bin/sh
# Local SSH testbed for the Servers module (docs/remote/PLAN.md §8.3).
#   sh scripts/remote-testbed/testbed.sh up     # keys + config + containers + workloads
#   sh scripts/remote-testbed/testbed.sh down   # remove everything
#   sh scripts/remote-testbed/testbed.sh keys   # (re)write keys + ssh_config only
#   sh scripts/remote-testbed/testbed.sh test   # up, integration tests, down (npm run test:remote)
# Then: NEXUS_SSH_CONFIG=$PWD/scripts/remote-testbed/ssh_config npm start
# Nothing here touches ~/.ssh: keys, config and known_hosts live in this folder.
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
KEYS="$HERE/.keys"
SOCK=unix:///var/run/dind/docker.sock
compose() { docker compose -f "$HERE/docker-compose.yml" "$@"; }

keys() {
  mkdir -p "$KEYS" && chmod 700 "$KEYS"
  [ -f "$KEYS/id_ed25519" ] || ssh-keygen -q -t ed25519 -N '' -C nexus-testbed -f "$KEYS/id_ed25519"
  # A key the servers don't accept, for the `auth` error path.
  [ -f "$KEYS/wrong_ed25519" ] || ssh-keygen -q -t ed25519 -N '' -C nexus-wrong -f "$KEYS/wrong_ed25519"
  good="IdentityFile \"$KEYS/id_ed25519\""
  cat > "$HERE/ssh_config" <<CFG
# Generated by testbed.sh — do not edit. IdentityFile accumulates across
# matching Host blocks, so each host names exactly one key.
Host nexus-dev
  Port 2221
  $good
Host nexus-staging
  Port 2222
  $good
Host nexus-prod
  Port 2223
  $good
# Same server as nexus-prod, but its own empty known_hosts: the host-key path.
Host nexus-unknown
  Port 2223
  $good
  UserKnownHostsFile "$HERE/known_hosts.unknown"
# The servers don't accept this key: the auth path.
Host nexus-badkey
  Port 2223
  IdentityFile "$KEYS/wrong_ed25519"
# Nothing listens here: the unreachable path.
Host nexus-closed
  Port 2229
  $good
# Routes nowhere: the timeout path.
Host nexus-blackhole
  HostName 10.255.255.1
  $good
Host nexus-*
  HostName 127.0.0.1
  User nexus
  IdentitiesOnly yes
  UserKnownHostsFile "$HERE/known_hosts"
CFG
}

up() {
  keys
  compose up -d --build --wait
  i=0
  until compose exec -T dockerd docker -H "$SOCK" info >/dev/null 2>&1; do
    i=$((i + 1)); [ "$i" -gt 60 ] && { echo "dind never came up" >&2; exit 1; }
    sleep 1
  done
  compose exec -T dockerd docker -H "$SOCK" compose -f - up -d --quiet-pull \
    < "$HERE/capture/workloads.compose.yml"
  # Trust the three real hosts (fresh keys on every build); leave
  # known_hosts.unknown empty so the host-key test starts from "never seen".
  : > "$HERE/known_hosts.unknown"
  : > "$HERE/known_hosts"
  for port in 2221 2222 2223; do
    j=0
    until ssh-keyscan -T 2 -t ed25519 -p "$port" 127.0.0.1 >> "$HERE/known_hosts" 2>/dev/null; do
      j=$((j + 1)); [ "$j" -gt 30 ] && { echo "sshd on :$port never came up" >&2; exit 1; }
      sleep 1
    done
  done
  echo "testbed up: NEXUS_SSH_CONFIG=$HERE/ssh_config"
}

down() { compose down -v --remove-orphans; }

# up → the ignored remote_it_* tests, one at a time (they share ssh masters) → down.
# Exits with the tests' status, not down's.
run_tests() {
  up
  rc=0
  NEXUS_SSH_CONFIG="$HERE/ssh_config" cargo test --manifest-path "$HERE/../../src-tauri/Cargo.toml" \
    remote_it_ -- --ignored --test-threads=1 --nocapture || rc=$?
  down
  exit "$rc"
}

case "${1:-}" in
  up) up ;;
  down) down ;;
  keys) keys ;;
  test) run_tests ;;
  *) echo "usage: testbed.sh up|down|keys|test" >&2; exit 2 ;;
esac
